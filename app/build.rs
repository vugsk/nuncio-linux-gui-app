// Шаг 5 из Архитектура/nuncio - Сборка и структура репозитория.md: здесь
// должна быть проверка, что `target/native/{libtgcrypto.a,libnuncio_net.a}`
// уже собраны (`just build`), и понятное сообщение вместо ошибки линковщика.
//
// Каркас (веха В0): линковки с .a ещё нет — `app` пока не вызывает ни Go,
// ни ядро (это «вертикаль-заглушка», следующий шаг В0). Поэтому здесь
// только предупреждение, не отказ сборки; когда появится реальная
// линковка (веха В3), эту функцию нужно заменить на panic! с инструкцией
// «выполните `just build`».
fn main() {
    let native = std::path::Path::new("../target/native");
    if !native.join("libtgcrypto.a").exists() {
        println!("cargo:warning=ядро ещё не собрано (just core) — app пока не линкуется с ним, это ожидаемо на вехе В0");
    }
    if !native.join("libnuncio_net.a").exists() {
        println!("cargo:warning=сеть ещё не собрана (just net) — app пока не линкуется с ней, это ожидаемо на вехе В0");
    }
}

// Command tlgen генерирует Go-кодек TL из схем в schema/ (шаг 1,
// `just tl`, см. Архитектура/nuncio - Сборка и структура репозитория.md).
//
// Каркас (веха В0): схемы (mtproto.tl, api.tl, used.txt) — пустые
// заготовки, поэтому генератор пока не разбирает TL по-настоящему —
// только читает схему и used.txt и отмечает факт запуска, чтобы шаг
// сборки был реальным, а не фиктивным. Настоящий разбор конструкторов
// и генерация кодека — веха В2.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

func countMeaningfulLines(path string) (int, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()
	n := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "//") || strings.HasPrefix(line, "#") {
			continue
		}
		n++
	}
	return n, sc.Err()
}

func main() {
	schemaDir := flag.String("schema", "../../schema", "каталог со схемами .tl и used.txt")
	outDir := flag.String("out", "../../net/tl", "куда писать сгенерированный код")
	flag.Parse()

	mtprotoLines, err := countMeaningfulLines(filepath.Join(*schemaDir, "mtproto.tl"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "tlgen: mtproto.tl:", err)
		os.Exit(1)
	}
	apiLines, err := countMeaningfulLines(filepath.Join(*schemaDir, "api.tl"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "tlgen: api.tl:", err)
		os.Exit(1)
	}
	usedLines, err := countMeaningfulLines(filepath.Join(*schemaDir, "used.txt"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "tlgen: used.txt:", err)
		os.Exit(1)
	}

	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "tlgen: mkdir:", err)
		os.Exit(1)
	}

	out := filepath.Join(*outDir, "generated.go")
	content := fmt.Sprintf(`// Code generated by tlgen. DO NOT EDIT.
// Сгенерировано: %s
//
// Каркас (веха В0): реального кодека нет, схема пуста-заготовка
// (строк схемы: mtproto.tl=%d, api.tl=%d, used.txt=%d). Настоящая
// генерация — веха В2, см. Архитектура/nuncio - План реализации.md.
package tl
`, time.Now().UTC().Format(time.RFC3339), mtprotoLines, apiLines, usedLines)

	if err := os.WriteFile(out, []byte(content), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "tlgen: write:", err)
		os.Exit(1)
	}
	fmt.Printf("tlgen: написан %s (mtproto.tl=%d, api.tl=%d, used.txt=%d строк)\n", out, mtprotoLines, apiLines, usedLines)
}
